const CATEGORY_MAP: Record<string, TranslationKey> = {
  RESIDENTIAL: "residentialLabel",
  COMMERCIAL: "commercialLabel",
  LAND: "landLabel",
};

export function translateRegion(code: string, t: (key: TranslationKey) => string): string {
  const key = REGION_CODE_MAP[code];
  return key ? t(key) : code;
}

export function translateType(type: string, t: (key: TranslationKey) => string): string {
  const key = TYPE_LABEL_MAP[type];
  return key ? t(key) : type.replaceAll("_", " ");
}

export function translateSort(value: string, t: (key: TranslationKey) => string): string {
  const key = SORT_LABEL_MAP[value];
  return key ? t(key) : value;
}

export function translateLegalStatus(value: string, t: (key: TranslationKey) => string): string {
  const key = LEGAL_STATUS_MAP[value];
  return key ? t(key) : value;
}

export function translateCategory(value: string, t: (key: TranslationKey) => string): string {
  const key = CATEGORY_MAP[value];
  return key ? t(key) : value;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("FR");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    const saved = localStorage.getItem("3a9ar-locale") as Locale | null;
    if (saved && ["FR", "EN", "AR"].includes(saved)) {
      setLocaleState(saved);
    }
    setMounted(true);
  }, []);

  useEffect(() => {
    if (!mounted) return;
    localStorage.setItem("3a9ar-locale", locale);
    document.documentElement.lang = locale === "AR" ? "ar" : locale === "FR" ? "fr" : "en";
    document.documentElement.dir = locale === "AR" ? "rtl" : "ltr";
  }, [locale, mounted]);

  const setLocale = (l: Locale) => {
    setLocaleState(l);
  };

  const t = (key: TranslationKey, params?: Record<string, string | number>): string => {
    const base = translations[locale][key] ?? translations.FR[key] ?? key;
    let text = base as string;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v));
      });
    }
    return text;
  };

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
